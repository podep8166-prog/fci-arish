import re

FAQ_DATABASE = {
    r".*(أقسام|تخصصات|قسم|تخصص).*": "كلية الحاسبات والمعلومات بجامعة العريش تضم 3 أقسام رئيسية وهي:\n1. علوم الحاسب (CS)\n2. نظم المعلومات (IS)\n3. تكنولوجيا المعلومات (IT)",
    r".*علوم (الحاسب|حاسب).*": "قسم علوم الحاسب (CS) يركز على البرمجة، الخوارزميات، الذكاء الاصطناعي، وهندسة البرمجيات.",
    r".*نظم (المعلومات|معلومات).*": "قسم نظم المعلومات (IS) يجمع بين الإدارة والتقنية، ويهتم بتحليل الأعمال، وقواعد البيانات، ونظم دعم القرار.",
    r".*تكنولوجيا (المعلومات|معلومات).*": "قسم تكنولوجيا المعلومات (IT) يركز على الشبكات، أمن المعلومات، الحوسبة السحابية، والبنية التحتية.",
    r".*(موقع|مكان|عنوان).*": "تقع كلية الحاسبات والمعلومات في الحرم الجامعي لجامعة العريش بمدينة العريش، محافظة شمال سيناء.",
    r".*(ساعات|نظام).*": "نظام الدراسة بالكلية يعتمد على نظام الساعات المعتمدة (Credit Hours)."
}

def get_faq_answer(user_message: str):
    """
    Checks if the user message matches a common FAQ using regex.
    Returns the answer if matched, else returns None.
    """
    for pattern, answer in FAQ_DATABASE.items():
        if re.search(pattern, user_message, re.IGNORECASE):
            return answer
    return None
